from __future__ import annotations

from pathlib import Path

from .analyzer import analyze_module, render_stub
from .loader import load_structured_file


def _relative_source_path(source: Path, cwd: Path) -> Path:
    source = source.resolve()
    cwd = cwd.resolve()

    try:
        return source.relative_to(cwd)
    except ValueError:
        return Path(source.name)


def _ensure_package_inits(target: Path, package_root: Path) -> None:
    current = target.parent

    while True:
        init_file = current / "__init__.pyi"
        if not init_file.exists():
            init_file.write_text("# generated by typegen\n", encoding="utf-8")

        if current == package_root:
            break

        current = current.parent


def generate_stub_for_file(
    source: str | Path,
    output_dir: str | Path,
    package_name: str = "_typegen",
    cwd: str | Path | None = None,
) -> Path:
    source = Path(source)
    output_dir = Path(output_dir)
    cwd = Path.cwd() if cwd is None else Path(cwd)

    data = load_structured_file(source)
    root_class = analyze_module(source.stem, data)

    package_root = output_dir / package_name
    relative = _relative_source_path(source, cwd).with_suffix(".pyi")
    target = package_root / relative

    target.parent.mkdir(parents=True, exist_ok=True)
    package_root.mkdir(parents=True, exist_ok=True)
    _ensure_package_inits(target, package_root)

    target.write_text(render_stub(root_class), encoding="utf-8")
    return target
